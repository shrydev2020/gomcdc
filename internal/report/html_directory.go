// HTML page budgets include navigation, styles and escaped text. A series keeps
// only its current page; children are separate documents, not hidden DOM.
const (
	htmlPageBytes             = 1 << 20
	htmlPageElements          = 5000
	htmlBodyBytes             = 512 << 10
	htmlBodyElements          = 3500
	htmlFieldBytes            = 1024
	htmlTextChunkBytes        = 16 << 10
	htmlIndexRows             = 100
	htmlEvaluationRowsPerPage = 200
)

type htmlDirectory struct {
	ctx                        context.Context
	dir, module, footer, style string
	err                        error
	sources                    map[string][]byte
	findings                   *htmlPages
	findingGroups              map[string]*htmlPages
}

type htmlPages struct {
	site                                    *htmlDirectory
	id, title, parent, intro, before, after string
	extra                                   func() string
	body                                    strings.Builder
	page, rows, total, elements, rowLimit   int
}

func htmlID(kind string, parts ...string) string {
	h := sha256.New()
	for _, p := range parts {
		fmt.Fprintf(h, "%d:", len(p))
		io.WriteString(h, p)
	}
	return fmt.Sprintf("%s-%x", kind, h.Sum(nil))
}
func htmlPageName(id string, page int) string { return fmt.Sprintf("%s-%d.html", id, page) }
func escape(s string) string                  { return html.EscapeString(s) }
func htmlLink(target, label string) string {
	return `<a href="` + escape(target) + `">` + label + `</a>`
}
func htmlElements(s string) int {
	n := 0
	for part := range strings.SplitSeq(s, "<") {
		if len(part) > 0 && ((part[0] >= 'a' && part[0] <= 'z') || (part[0] >= 'A' && part[0] <= 'Z')) {
			n++
		}
	}
	return n
}
func htmlPrefix(s string, limit int) string {
	if len(s) <= limit {
		return s
	}
	original := limit
	for limit > 0 && !utf8.RuneStart(s[limit]) {
		limit--
	}
	if limit == 0 {
		limit = original
	}
	return s[:limit]
}

// WriteHTMLDirectory publishes a complete, offline report. Only index.html is
// replaced. Older generations stay readable by already-open browser tabs.
// It reads immutable analysis/source inputs; it never measures or analyzes.
func WriteHTMLDirectory(ctx context.Context, directory string, value analysis.Result, sources []analysis.SourceFileInput) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if err := os.MkdirAll(directory, 0755); err != nil {
		return err
	}
	stage, err := os.MkdirTemp(directory, ".gomcdc-html-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	s := &htmlDirectory{ctx: ctx, dir: stage, module: value.Module, sources: make(map[string][]byte), findingGroups: make(map[string]*htmlPages)}
	for _, source := range sources {
		s.sources[source.PackagePath+"\x00"+source.Path] = source.Source
	}
	s.footer = "Generated by gomcdc " + escape(htmlPrefix(value.ToolVersion, 128)) + " (report schema " + escape(htmlPrefix(value.SchemaVersion, 128)) + "). Offline HTML and CSS. Copy the entire report directory."
	// Reuse the report's colors and source-mode selectors without its all-data DOM.
	start := strings.Index(htmlDocument, "<style>")
	end := strings.Index(htmlDocument, "</style>") + len("</style>")
	t, err := template.New("styles").Funcs(template.FuncMap{"sourceModes": htmlSourceModes}).Parse(htmlDocument[start:end])
	if err != nil {
		return err
	}
	var css bytes.Buffer
	if err = t.Execute(&css, nil); err != nil {
		return err
	}
	s.style = css.String() + `<style>.pagination{display:flex;gap:1rem;align-items:center;flex-wrap:wrap;margin:1rem 0}.side a{overflow-wrap:anywhere}.table th{white-space:normal}.source-code a{color:inherit}.source-code [id]:target{outline:2px solid var(--link)}.source-line{color:var(--muted);font-size:.75rem}.panel p{overflow-wrap:anywhere}.evidence-context{white-space:pre-wrap}.field{white-space:pre-wrap}.finding{content-visibility:visible}.side .nav a{white-space:normal}.status-covered{background:var(--good)}</style>`
	cssText := strings.NewReplacer("<style>", "", "</style>", "").Replace(s.style)
	s.write("style.css", []byte(cssText))
	s.style = `<link rel="stylesheet" href="style.css">`
	s.render(value)
	if s.err != nil {
		return fmt.Errorf("render HTML directory: %w", s.err)
	}
	digest, err := htmlGenerationDigest(ctx, stage, true)
	if err != nil {
		return err
	}
	generation := "report-" + digest
	target := filepath.Join(directory, generation)
	if _, statErr := os.Lstat(target); statErr == nil {
		existing, checkErr := htmlGenerationDigest(ctx, target, true)
		if checkErr != nil || existing != digest {
			return fmt.Errorf("existing HTML generation is not complete: %s", target)
		}
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return statErr
	} else if err = os.Rename(stage, target); err != nil {
		existing, checkErr := htmlGenerationDigest(ctx, target, true)
		if checkErr != nil || existing != digest {
			return fmt.Errorf("publish HTML generation: %w", err)
		}
	}
	if err = ctx.Err(); err != nil {
		return err
	}
	entry, err := os.ReadFile(filepath.Join(target, "overview-1.html"))
	if err != nil {
		return err
	}
	// All page references are renderer-owned relative filenames.
	entry = bytes.ReplaceAll(entry, []byte(`href="`), []byte(`href="`+generation+`/`))
	f, err := os.CreateTemp(directory, ".index.html-")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(entry); err == nil {
		err = f.Sync()
	}
	err = errors.Join(err, f.Close())
	if err != nil {
		return err
	}
	if err = os.Chmod(f.Name(), 0644); err != nil {
		return err
	}
	if err = ctx.Err(); err != nil {
		return err
	}
	return os.Rename(f.Name(), filepath.Join(directory, "index.html"))
}

var htmlHref = regexp.MustCompile(`href="([^"]+)"`)

// Validation is disk-backed and bounded by one page, not an in-memory manifest
// containing all evidence. Hashes include filenames to protect reuse as well.
func htmlGenerationDigest(ctx context.Context, dir string, checkLinks bool) (string, error) {
	info, err := os.Lstat(dir)
	if err != nil {
		return "", err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return "", fmt.Errorf("HTML generation is not a directory: %s", dir)
	}
	h := sha256.New()
	err = filepath.WalkDir(dir, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		if path == dir {
			return nil
		}
		if !d.Type().IsRegular() {
			return fmt.Errorf("unexpected HTML generation entry %s", path)
		}
		name := d.Name()
		f, err := os.Open(path)
		if err != nil {
			return err
		}
		digest := sha256.New()
		_, err = io.Copy(digest, f)
		err = errors.Join(err, f.Close())
		if err != nil {
			return err
		}
		fmt.Fprintf(h, "%d:%s:%x\n", len(name), name, digest.Sum(nil))
		if strings.HasSuffix(name, ".html") {
			info, err := d.Info()
			if err != nil {
				return err
			}
			if info.Size() > htmlPageBytes {
				return fmt.Errorf("HTML page exceeds byte budget: %s", name)
			}
			content, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if htmlElements(string(content)) > htmlPageElements {
				return fmt.Errorf("HTML page exceeds element budget: %s", name)
			}
			if checkLinks {
				for _, m := range htmlHref.FindAllSubmatch(content, -1) {
					dest, _, _ := strings.Cut(html.UnescapeString(string(m[1])), "#")
					if dest == "" || filepath.Base(dest) != dest {
						return fmt.Errorf("invalid page link: %s", m[1])
					}
					linked, err := os.Lstat(filepath.Join(dir, dest))
					if err != nil {
						return fmt.Errorf("broken page link %s: %w", dest, err)
					}
					if !linked.Mode().IsRegular() {
						return fmt.Errorf("nonregular link target: %s", dest)
					}
				}
			}
		}
		return nil
	})
	return fmt.Sprintf("%x", h.Sum(nil)), err
}

func (s *htmlDirectory) write(name string, content []byte) {
	if s.err != nil {
		return
	}
	if s.err = s.ctx.Err(); s.err != nil {
		return
	}
	f, err := os.OpenFile(filepath.Join(s.dir, name), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
	if err != nil {
		s.err = err
		return
	}
	_, err = f.Write(content)
	s.err = errors.Join(err, f.Close())
}
func (s *htmlDirectory) pages(id, title, parent, intro, before, after string, limit int) *htmlPages {
	return &htmlPages{site: s, id: id, title: htmlPrefix(title, 256), parent: parent, intro: intro, before: before, after: after, page: 1, rowLimit: limit}
}
func (p *htmlPages) link() string { return htmlPageName(p.id, 1) }
func (p *htmlPages) add(item string) int {
	if p.site.err != nil {
		return p.page
	}
	nodes := htmlElements(item)
	if len(item) > htmlBodyBytes || nodes > htmlBodyElements {
		p.site.err = fmt.Errorf("HTML item exceeds page budget in %s", p.id)
		return p.page
	}
	if p.rows > 0 && (p.rows >= p.rowLimit || p.body.Len()+len(item) > htmlBodyBytes || p.elements+nodes > htmlBodyElements) {
		p.flush(true)
	}
	p.body.WriteString(item)
	p.rows++
	p.total++
	p.elements += nodes
	return p.page
}
func (p *htmlPages) close() { p.flush(false) }
func (p *htmlPages) nav(next bool) string {
	if p.page == 1 && !next {
		return ""
	}
	var b strings.Builder
	b.WriteString(`<nav class="pagination" aria-label="Pages">`)
	if p.page > 1 {
		b.WriteString(htmlLink(p.link(), "First"))
		b.WriteString(htmlLink(htmlPageName(p.id, p.page-1), "Previous"))
	}
	fmt.Fprintf(&b, `<span>Page %d · items %d–%d</span>`, p.page, max(0, p.total-p.rows+1), p.total)
	if next {
		b.WriteString(htmlLink(htmlPageName(p.id, p.page+1), "Next"))
	}
	b.WriteString(`</nav>`)
	return b.String()
}
func (p *htmlPages) flush(next bool) {
	s := p.site
	if s.err != nil {
		return
	}
	empty := ""
	if p.rows == 0 {
		empty = `<p class="emptymsg">No entries in this section.</p>`
	}
	var b strings.Builder
	b.WriteString(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>` + escape(p.title) + ` — gomcdc</title>` + s.style + `</head><body><div class="layout"><aside class="side" aria-label="Package navigation"><div class="brand">gomcdc</div><div class="module">` + escape(htmlPrefix(s.module, 256)) + `</div><ul class="nav">`)
	for _, link := range [][2]string{{"overview-1.html", "Overview"}, {"packages-1.html", "Packages"}, {"findings-1.html", "Findings"}, {"producers-1.html", "Evidence producers"}} {
		b.WriteString("<li>" + htmlLink(link[0], link[1]) + "</li>")
	}
	if p.parent != "" {
		b.WriteString("<li>" + htmlLink(p.parent, "Back to parent") + "</li>")
	}
	b.WriteString(`</ul></aside><main class="main"><header><p class="eyebrow">Coverage report</p><h1>` + escape(p.title) + `</h1></header>` + p.intro + p.extraHTML() + p.nav(next) + `<section class="panel">` + empty + p.before + p.body.String() + p.after + `</section>` + p.nav(next) + `<footer class="footer">` + s.footer + `</footer></main></div></body></html>`)
	content := b.String()
	if len(content) > htmlPageBytes || htmlElements(content) > htmlPageElements {
		s.err = fmt.Errorf("HTML page budget exceeded: %s", p.id)
		return
	}
	s.write(htmlPageName(p.id, p.page), []byte(content))
	p.body.Reset()
	p.rows = 0
	p.elements = 0
	p.page++
}

// Long user strings are continued in bounded text pages, never silently dropped
// or concatenated into a page-sized attribute. Hash IDs allow disk-based reuse.
func (s *htmlDirectory) field(value string) string {
	if len(value) <= htmlFieldBytes {
		if strings.ContainsAny(value, "\t\r\n") || strings.Contains(value, "  ") {
			return `<span class="field">` + escape(value) + `</span>`
		}
		return escape(value)
	}
	id := htmlID("text", value)
	if _, err := os.Stat(filepath.Join(s.dir, htmlPageName(id, 1))); errors.Is(err, os.ErrNotExist) {
		p := s.pages(id, "Full text", "overview-1.html", "", `<pre class="evidence-context">`, `</pre>`, 8)
		for rest := value; rest != "" && s.err == nil; {
			chunk := htmlPrefix(rest, htmlTextChunkBytes)
			p.add(escape(chunk))
			rest = rest[len(chunk):]
		}
		p.close()
	} else if err != nil {
		s.err = err
	}
	return `<span class="field">` + escape(htmlPrefix(value, 256)) + `… ` + htmlLink(htmlPageName(id, 1), "Full text") + `</span>`
}
func (s *htmlDirectory) paragraph(label, value string) string {
	return "<p><strong>" + escape(label) + ":</strong> " + s.field(value) + "</p>"
}
func (s *htmlDirectory) status(value string) string {
	return `<span class="status status-` + escape(htmlPrefix(value, 64)) + `">` + s.field(value) + `</span>`
}
func (s *htmlDirectory) metrics(summary analysis.Summary) string {
	var b strings.Builder
	b.WriteString(`<div class="metrics">`)
	for _, m := range htmlMetrics(summary) {
		fmt.Fprintf(&b, `<div class="metric %s"><div class="name" title="%s">%s</div>%s<div class="value">%s</div><div>%d / %d</div><small>unknown %d · unsupported %d · infeasible %d · analysis-incomplete %d</small></div>`, htmlMetricClass(m.Summary), m.Name, m.Short, s.status(htmlMetricStatus(m.Summary)), htmlPercentage(m.Summary), m.Summary.Covered, m.Summary.Total, m.Summary.Unknown, m.Summary.Unsupported, m.Summary.Infeasible, m.Summary.AnalysisIncomplete)
	}
	b.WriteString(`</div>`)
	return b.String()
}

func (p *htmlPages) extraHTML() string {
	if p.extra != nil {
		return p.extra()
	}
	return ""
}

func (s *htmlDirectory) link(target, value string) string {
	label := htmlPrefix(value, 256)
	if len(value) <= htmlFieldBytes {
		return htmlLink(target, escape(value))
	}
	return htmlLink(target, escape(label)+"…") + " " + s.field(value)
}
