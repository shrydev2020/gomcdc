package report

import (
	"context"
	"fmt"
	"strings"

	"github.com/shrydev2020/gomcdc/v2/internal/analysis"
)

type htmlSourceKey struct{ packagePath, path string }

type htmlReportRenderer struct {
	output        *htmlPageWriter
	sources       map[htmlSourceKey][]byte
	findings      *htmlPageSeries
	findingGroups map[string]*htmlPageSeries
}

func renderHTMLDirectory(ctx context.Context, directory string, value analysis.Result, sources []analysis.SourceFileInput) error {
	output := &htmlPageWriter{ctx: ctx, dir: directory, module: value.Module,
		footer: "Generated by gomcdc " + escape(htmlPrefix(value.ToolVersion, 128)) + " (report schema " + escape(htmlPrefix(value.SchemaVersion, 128)) + "). Offline HTML and CSS. Copy the entire report directory."}
	renderer := &htmlReportRenderer{output: output, sources: make(map[htmlSourceKey][]byte, len(sources)), findingGroups: make(map[string]*htmlPageSeries)}
	for _, source := range sources {
		key := htmlSourceKey{source.PackagePath, source.Path}
		if _, exists := renderer.sources[key]; exists {
			return fmt.Errorf("duplicate original source for package %q, file %q", source.PackagePath, source.Path)
		}
		renderer.sources[key] = source.Source
	}
	styles, err := renderHTMLStyles()
	if err != nil {
		return err
	}
	output.write("style.css", styles)
	renderer.render(value)
	return output.err
}

func (s *htmlReportRenderer) metrics(summary analysis.Summary) string {
	var b strings.Builder
	b.WriteString(`<div class="metrics">`)
	for _, m := range htmlMetrics(summary) {
		fmt.Fprintf(&b, `<div class="metric %s"><div class="name" title="%s">%s</div>%s<div class="value">%s</div><div>%d / %d</div><small>unknown %d · unsupported %d · infeasible %d · analysis-incomplete %d</small></div>`, htmlMetricClass(m.Summary), m.Name, m.Short, s.output.status(htmlMetricStatus(m.Summary)), htmlPercentage(m.Summary), m.Summary.Covered, m.Summary.Total, m.Summary.Unknown, m.Summary.Unsupported, m.Summary.Infeasible, m.Summary.AnalysisIncomplete)
	}
	b.WriteString(`</div>`)
	return b.String()
}
